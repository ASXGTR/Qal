using UnityEngine;

public class AudioManager : MonoBehaviour
{
    // ---------------------------------------------------------
    // SINGLETON INSTANCE
    // ---------------------------------------------------------
    // AudioManager is implemented as a Singleton so that all systems
    // in the project (FSK encoder, Owner Mode, diagnostics, etc.)
    // can access a single shared AudioSource.
    //
    // This ensures consistent audio behaviour and prevents multiple
    // AudioManager objects from being created accidentally.
    public static AudioManager Instance;

    // ---------------------------------------------------------
    // PRIMARY AUDIO SOURCE (Ultrasonic / FSK Playback)
    // ---------------------------------------------------------
    // This AudioSource is used for all ultrasonic / FSK playback
    // during the demo. The encoder assigns generated AudioClips to
    // this AudioSource when transmitting encoded authentication data.
    //
    // IMPORTANT NOTE FOR ENGINEERS / OEM REVIEWERS:
    // In this demonstration environment, ultrasonic audio is played
    // through consumer laptop speakers. These speakers typically apply
    // automatic DSP processing such as:
    //
    //   - dynamic range compression
    //   - EQ enhancement
    //   - virtualization / stereo widening
    //   - “audio improvement” filters
    //
    // These effects distort high‑frequency signals and interfere with
    // clean FSK transmission. Because of this, the AudioManager is
    // suitable for demonstration purposes only.
    //
    // Reliable ultrasonic output in real‑world conditions requires
    // playback from a user’s mobile device or dedicated hardware
    // capable of producing clean, unprocessed high‑frequency audio.
    //
    // The demo pipeline is intentionally simplified to illustrate the
    // authentication concept rather than provide production‑grade
    // ultrasonic modem performance.
    public AudioSource audioSource;

    // ---------------------------------------------------------
    // UNITY LIFECYCLE: Awake()
    // ---------------------------------------------------------
    // Awake() runs before Start() and is used here to enforce the
    // Singleton pattern. If an AudioManager already exists, any new
    // instance is destroyed to avoid duplicates.
    //
    // DontDestroyOnLoad() ensures the AudioManager persists across
    // scene changes, maintaining continuous audio behaviour.
    void Awake()
    {
        if (Instance == null)
        {
            Instance = this;
            DontDestroyOnLoad(gameObject);   // Persist between scenes
        }
        else
        {
            Destroy(gameObject);             // Prevent duplicate managers
        }
    }

    // ---------------------------------------------------------
    // CONFIGURE AUDIO SOURCE FOR FSK OUTPUT
    // ---------------------------------------------------------
    // This method configures the AudioSource for transmitting
    // ultrasonic FSK (Frequency Shift Keying) signals.
    //
    // Unity applies several audio processing effects by default,
    // including spatialization, reverb zones, and listener effects.
    // These effects distort high‑frequency encoded signals and prevent
    // the decoder from receiving clean data.
    //
    // ConfigureForFSK() disables all Unity DSP processing so the
    // AudioSource outputs raw PCM data exactly as generated by the
    // encoder. This is critical for reliable decoding.
    public void ConfigureForFSK()
    {
        audioSource.bypassEffects = true;          // Disable AudioSource effects
        audioSource.bypassListenerEffects = true;  // Disable AudioListener effects
        audioSource.bypassReverbZones = true;      // Disable environmental reverb
        audioSource.spatialBlend = 0f;             // Force 2D audio (no spatialization)
    }
}
